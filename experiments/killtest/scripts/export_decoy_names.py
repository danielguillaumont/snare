"""Export per-install decoy names from the Go code for the M3a-fix evaluation.

The names come from `snare decoys` (internal/decoys), so the product and the harness share one
source of truth. Run from the repo root:

    python experiments/killtest/scripts/export_decoy_names.py

It builds the snare binary, simulates 40 installs (seeds 1..40) in snake_case, which matches
the harness's real tools as an operator would, and records every name the generator can
produce (what a code-reading attacker can enumerate).
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

INSTALLS = 40
OUT = Path("experiments/killtest/killtest/data/decoy_names_fix.json")


def main() -> int:
    exe = Path(tempfile.gettempdir()) / ("snare-export" + (".exe" if sys.platform == "win32" else ""))
    subprocess.run(["go", "build", "-o", str(exe), "./cmd/snare"], check=True)
    installs = []
    for seed in range(1, INSTALLS + 1):
        rows = json.loads(subprocess.check_output([str(exe), "decoys", "-seed", str(seed), "-style", "snake"]))
        installs.append({"seed": seed, "names": {r["canonical"]: r["name"] for r in rows}})
    all_names = json.loads(subprocess.check_output([str(exe), "decoys", "-all"]))
    out = {
        "_source": "generated by scripts/export_decoy_names.py from `snare decoys` (internal/decoys); do not edit",
        "installs": installs,
        "all_generated": all_names,
    }
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(installs)} installs, {len(all_names)} generated names")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
